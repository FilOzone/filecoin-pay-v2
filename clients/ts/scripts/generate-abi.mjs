// Writes src/abi/generated.ts from the compiled FilecoinPayV2 contract. Needs Foundry.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const abi = JSON.parse(
  execFileSync('forge', ['inspect', 'FilecoinPayV2', 'abi', '--json'], {
    cwd: new URL('../../../', import.meta.url),
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
)

writeFileSync(
  new URL('../src/abi/generated.ts', import.meta.url),
  `// Generated by scripts/generate-abi.mjs from \`forge inspect FilecoinPayV2 abi\`. Do not edit.

export const filecoinPayV2Abi = ${JSON.stringify(abi, null, 2)} as const
`
)
